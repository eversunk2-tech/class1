/** 처리방침 화면의 글 덩어리 */
export type PolicyBlock =
  | { type: "paragraph"; text: string }
  /** 쉬운 설명의 굵은 질문 줄처럼, 덩어리 안의 작은 제목 */
  | { type: "subheading"; text: string }
  | { type: "list"; ordered?: boolean; items: readonly string[] }
  | { type: "table"; head: readonly string[]; rows: readonly (readonly string[])[] };

export type PolicyArticle = { title: string; blocks: readonly PolicyBlock[] };

/** 별명·코드 칸의 이름과 도움말(원문 "**별명** (2~20자, 실명 대신 별명)") */
export type GateField = { label: string; hint: string };

